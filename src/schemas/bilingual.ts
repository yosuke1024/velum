import { z } from 'zod';

/**
 * 二言語の一文。サイトは 1言語 = 1 URL で、`/velum/en/` は英語しか出さない場所
 * である。読み出し側の作法は `src/lib/bilingual.ts` に書いてある。
 */
export const Bilingual = z.object({
  ja: z.string().min(1),
  en: z.string().min(1),
});

/**
 * かつてここには `MaybeBilingual`（`Bilingual | string`）があった。素の文字列を
 * 「未訳」として受け、読む側が ja へ落とすので英語ページには日本語が出る——
 * 無言で消すよりは見えているほうがよい、という判断だった。
 *
 * その判断は、掲載側に言語ガードが入った時点で保たなくなった。未訳の欄は
 * 「見えている欠陥」ではなく**その日の公開が丸ごと止まる原因**になる。実際に
 * 2026-09-01、最初の日記が `/velum/en/` へ日本語の信念キーを出して同期が
 * 止まった。緩いままだった `canon.facts` と季の計画も同じ形をしていた。
 *
 * いまは、読み手へ渡る欄はすべて `Bilingual` である。生成はその場で両方書く
 * （日記も、追記する canon の事実も、季の計画も）。欠けたらここで落ちる。
 *
 * 読み出しの `pick()` / `both()`（`src/lib/bilingual.ts`）は素の文字列も受ける
 * ままにしてある。あちらは束を読む側の作法で、こちらは書く側の契約である。
 */
